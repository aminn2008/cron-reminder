function getLang() {
  try {
    return localStorage.getItem('lang') === 'fa' ? 'fa' : 'en';
  } catch (e) {
    return 'en';
  }
}

function t(key) {
  const table = I18N[getLang()] || I18N.en;
  return table[key] != null ? table[key] : (I18N.en[key] != null ? I18N.en[key] : key);
}

function tWith(key, vars) {
  let s = t(key);
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', v);
  return s;
}

function faNum(n) {
  return String(n).replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[d]);
}

function setLang(lang) {
  try {
    localStorage.setItem('lang', lang);
  } catch (e) {}
  applyLang();
}

function applyLang() {
  const lang = getLang();
  const fa = lang === 'fa';
  document.documentElement.lang = lang;
  document.documentElement.dir = fa ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  const btn = document.getElementById('lang-toggle');
  if (btn) btn.textContent = fa ? 'English' : 'فارسی';
  window.dispatchEvent(new CustomEvent('langchange'));
}

function initI18n() {
  const btn = document.getElementById('lang-toggle');
  if (btn) {
    btn.addEventListener('click', () => setLang(getLang() === 'en' ? 'fa' : 'en'));
  }
  applyLang();
}

initI18n();
